/**
 * Wire contract for `GET /api/fact`, shared by the route handler and the UI.
 *
 * Types and constants only, so Client Components can import this file without
 * pulling any server code into the browser bundle.
 */

/** A fact is served from cache while it is younger than this. */
export const FACT_CACHE_WINDOW_MS = 60_000;

export type FactDTO = {
  id: string;
  /** The movie title this fact was generated for. */
  movie: string;
  text: string;
  /** ISO-8601 timestamp. */
  createdAt: string;
};

/**
 * - `fresh`:  this request generated the fact.
 * - `cached`: the fact is younger than the cache window. It may have been
 *             generated by a concurrent request (another tab, a fast refresh).
 * - `stale`:  generation failed, so the most recent older fact is served.
 */
export type FactStatus = "fresh" | "cached" | "stale";

export type FactSuccess = {
  fact: FactDTO;
  status: FactStatus;
  /**
   * Milliseconds until the cache window closes and a new fact can be generated.
   * Relative rather than absolute so a skewed client clock cannot distort it.
   * Always 0 when `status` is `stale`.
   */
  freshForMs: number;
};

/**
 * HTTP status per code:
 * - `UNAUTHENTICATED`   401  no valid session
 * - `NO_MOVIE`          409  the user has not finished onboarding
 * - `GENERATION_FAILED` 503  OpenAI failed and there is no earlier fact to fall back to
 */
export type FactErrorCode = "UNAUTHENTICATED" | "NO_MOVIE" | "GENERATION_FAILED";

export type FactError = {
  error: { code: FactErrorCode; message: string };
};
